//! Deskboxes' own strings. Everything Windows shows (verbs, "Open with", "Properties", ...) is read
//! from Windows itself in the shell host; only our own commands are translated here.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    Pl,
    En,
}

impl Lang {
    /// "pl" / "en" / anything else = follow the Windows UI language (`ui_lang_id` = LANGID).
    pub fn pick(setting: &str, ui_lang_id: u16) -> Lang {
        match setting {
            "pl" => Lang::Pl,
            "en" => Lang::En,
            _ if ui_lang_id & 0x3ff == 0x15 => Lang::Pl, // LANG_POLISH
            _ => Lang::En,
        }
    }
    pub fn code(self) -> &'static str {
        match self {
            Lang::Pl => "pl",
            Lang::En => "en",
        }
    }
}

